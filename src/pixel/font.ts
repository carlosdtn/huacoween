export const textWidth = (text: string, scale = 1) =>
  (text.length * 4 - 1) * scale;

/** Draws uppercase text with its top-left corner at (x, y); `scale` makes chunkier signs. */
export const drawText = (
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
): void => {
  ctx.fillStyle = color;
  [...text.toUpperCase()].forEach((char, i) => {
    const rows = (GLYPHS[char] ?? GLYPHS[" "]).split("/");
    rows.forEach((row, dy) => {
      for (let dx = 0; dx < 3; dx++) {
        if (row[dx] === "#")
          ctx.fillRect(x + (i * 4 + dx) * scale, y + dy * scale, scale, scale);
      }
    });
  });
};

export const hasGlyph = (char: string) => char.toUpperCase() in GLYPHS;
